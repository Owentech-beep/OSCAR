import assert from "node:assert/strict";
import mongoose from "mongoose";

import {
  connectDatabase,
  disconnectDatabase,
} from "../config/db.js";

import {
  addMessage,
  getConversation,
  clearConversation,
} from "../services/oscar-memory.service.js";

const userA = new mongoose.Types.ObjectId().toString();
const userB = new mongoose.Types.ObjectId().toString();

async function main() {
  await connectDatabase();

  try {
    assert.deepEqual(await getConversation(userA), []);

    // Write more than the retained message limit.
    for (let index = 1; index <= 25; index++) {
      await addMessage(userA, "user", `Test message ${index}`);
    }

    await addMessage(userB, "user", "Separate user conversation");

    const historyA = await getConversation(userA);
    const historyB = await getConversation(userB);

    assert.equal(historyA.length, 20);
    assert.equal(historyA[0].content, "Test message 6");
    assert.equal(historyA[19].content, "Test message 25");

    assert.equal(historyB.length, 1);
    assert.equal(historyB[0].content, "Separate user conversation");

    console.log("PASS: latest 20 messages retained");
    console.log("PASS: conversations separated by user");

    // Close the connection and read again through a new connection.
    await disconnectDatabase();
    await connectDatabase();

    const reloaded = await getConversation(userA);

    assert.equal(reloaded.length, 20);
    assert.equal(reloaded[0].content, "Test message 6");
    assert.equal(reloaded[19].content, "Test message 25");

    console.log("PASS: history survives database reconnection");

    await clearConversation(userA);

    assert.deepEqual(await getConversation(userA), []);
    assert.equal((await getConversation(userB)).length, 1);

    console.log("PASS: clearing one conversation preserves the other");
  } finally {
    // Cleanup targets only the two IDs generated by this script.
    try {
      if (mongoose.connection.readyState !== 1) {
        await connectDatabase();
      }

      await Promise.all([
        clearConversation(userA),
        clearConversation(userB),
      ]);

      console.log("Temporary test conversations removed");
    } finally {
      await disconnectDatabase();
    }
  }
}

main().catch((error) => {
  console.error("Conversation memory test failed:", error.message);
  console.error("Test IDs, if cleanup is needed:", { userA, userB });
  process.exitCode = 1;
});